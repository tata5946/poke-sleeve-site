import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createContext, runInContext } from 'node:vm';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const p = createRequire(import.meta.url)('../assets/pricing.js');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const today = '2026-10-12';
const fixture = { releaseDate: '2020-06-12', firstPrice: 0, weeklyPrices: [], monthlyPrices: [], yearlyPrices: [] };
assert.equal(p.quote(fixture), null);
assert.ok(p.observationHtml(fixture, today).includes('参考相場を算出できるデータがありません'));
assert.equal(p.firstPrice(fixture).label, '価格不明');
assert.equal(p.firstPrice({ ...fixture, firstPriceStatus: 'free' }).label, '価格不明', 'Zero alone cannot establish a free distribution');
assert.equal(p.firstPrice({ ...fixture, firstPriceStatus: 'free', firstPriceEvidence: '公式無料配布資料' }).label, '無料配布');
assert.equal(p.firstPrice({ ...fixture, firstPriceStatus: 'set', firstPriceEvidence: 'セット収録資料' }).label, '単品定価なし');
const one = { ...fixture, weeklyPrices: [{ week: '2026-09-28', price: 1436.5, count: 1 }] };
assert.equal(p.quote(one).price, 1437);
assert.ok(p.notices(one, today).includes('取引件数が少ないため参考値'));
const monthly = { ...fixture, monthlyPrices: [{ month: '2026-02-01', price: 4100 }] };
assert.equal(p.quote(monthly).type, 'monthly');
assert.equal(p.quote(monthly).price, 4100);
assert.equal(p.weeklyPair(monthly), null, 'Monthly fallback does not produce a weekly comparison');
const mixed = { ...fixture, weeklyPrices: [{ week: '2025-11-01', price: 1778, count: 1 }, { week: '2026-08-03', price: 5556, count: 1 }] };
assert.equal(p.weeklyPair(mixed).prev, null, 'Legacy monthly price cannot be labeled as a previous weekly observation');
assert.equal(p.weeklyPair(mixed).sorted.length, 1, 'The shared pair retains the sorted weekly history used by growth and sparkline features');
assert.ok(p.observationHtml(monthly, today).includes('月次データから算出'));
const yearly = { ...fixture, yearlyPrices: [{ year: 2024, price: 3500 }] };
assert.equal(p.quote(yearly).type, 'yearly');
assert.equal(p.periodLabel(p.quote(yearly)), '2024年');
assert.ok(p.notices(yearly, today).includes('直近の取引データが少ない商品'));
const invalid = { ...fixture, weeklyPrices: [{ week: '2020-05-25', price: 999, count: 1 }, { week: '2026-09-28', price: 888, count: 0 }] };
assert.equal(p.quote(invalid), null, 'Pre-release and zero-transaction observations are not prices');
assert.equal(invalid.weeklyPrices[0].price, 999, 'Raw data must remain available for review');
const newest = { ...one, monthlyPrices: [{ month: '2026-10-01', price: 2000 }] };
assert.equal(p.quote(newest).price, 1437, 'Weekly observations have priority over coarse monthly aggregates');
assert.equal(p.quote(newest).count, 1, 'Monthly aggregate cannot hide the weekly transaction count');
assert.equal(p.periodKind('2026-06-01'), 'week', 'A Monday on day 01 is still a weekly observation');
assert.equal(p.periodKind('2025-06-01'), 'month', 'Legacy monthly records retain their source granularity');
assert.equal(p.sheetCount(one), 64);
assert.equal(p.unitPrice(one), '約22円');
const counted = { ...one, sheetCount: 62, sheetCountEvidence: '62枚販売カテゴリ' };
assert.equal(p.unitPrice(counted), '約23円');
for (const count of [10, 30, 32, 60, 62, 65]) {
  const rawGas = { ...one, categories: [count + '枚販売'] };
  assert.equal(p.sheetCount(rawGas), count, 'Read GAS size category directly');
  assert.equal(p.unitPrice(rawGas), '約' + p.yen(1437 / count));
}
assert.equal(p.sheetCount({ ...one, category6: '３２枚販売' }), 32);
assert.equal(p.sheetCount({ ...one, categories: ['32枚販売', '62枚販売'] }), null);
assert.equal(p.unitPrice(fixture), '-');
const spike = { ...one, weeklyPrices: [{ week: '2026-09-14', price: 7999, count: 1 }, { week: '2026-09-28', price: 35000, count: 1 }] };
assert.ok(p.notices(spike, today).some(note => note.includes('元取引の確認')));
const data = JSON.parse(read('data.json'));
const template = read('detail.html');
const source = [...template.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/gi)].find(match => match[2].includes('function buildAiMarketDiagnosis'))[2];
const elements = new Map();
const element = id => { if (!elements.has(id)) elements.set(id, { innerHTML: '', textContent: '', querySelector: () => null }); return elements.get(id); };
const context = createContext({ console, Date, Intl, URL, URLSearchParams, setTimeout, clearTimeout,
  window: { matchMedia: () => ({ matches: false }), addEventListener() {}, common: null },
  document: { getElementById: element, addEventListener() {}, querySelector: () => null, querySelectorAll: () => [], baseURI: 'https://pokesuri-navi.com/' },
  location: { href: 'https://pokesuri-navi.com/', search: '', pathname: '/' }, navigator: {}, localStorage: { getItem: () => null } });
runInContext(read('assets/pricing.js') + '\n' + source, context);
const decode = text => text.replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n))).replace(/&amp;/g, '&');
const content = (html, id) => decode(html.match(new RegExp(`<([\\w-]+)\\b[^>]*\\bid="${id}"[^>]*>([\\s\\S]*?)<\\/\\1>`))?.[2] || '').replace(/<[^>]*>/g, '').trim();
const records = [];
for (const sleeve of data.sleeves) {
  const id = String(sleeve.id), route = /^\d{6,7}$/.test(id) ? '4521329' + id : id;
  const html = read('sleeve/' + route + '/index.html');
  const q = p.quote(sleeve);
  const staticPrice = content(html, 'latestWeekly');
  const staticUnit = content(html, 'weeklyUnitPrice');
  assert.equal(staticPrice, p.yen(q?.price), id + ': static quote');
  assert.equal(staticUnit, p.unitPrice(sleeve), id + ': static unit price');
  assert.ok(/id="weeklyCount"/.test(html) && /id="referenceTradeCount"/.test(html), id + ': initial observation and count');
  assert.ok(content(html, 'weeklyCount').includes(q?.type === 'weekly' ? q.date.replaceAll('-', '/') : p.periodLabel(q)), id + ': observation period');
  assert.ok(content(html, 'referenceTradeCount').includes(q?.count != null ? q.count + '件' : '確認できません'), id + ': adopted count');
  assert.ok(decode(html).includes(p.firstPrice(sleeve).label), id + ': retail status');
  if (!q) assert.doesNotMatch(html, /<script[^>]*src="https:\/\/pagead2/, id + ': no price data, no ad loader');
  const embedded = JSON.parse(html.match(/window\.__SLEEVE_PAGE_DATA = (.*?);<\/script>/)[1]);
  assert.deepEqual(embedded, p.sanitizeSleeve(sleeve), id + ': same sanitized input as browser');
  context.sleeve = sleeve;
  runInContext('setPriceKpiFromSeries(buildFullPeriodSeries(sleeve), sleeve)', context);
  assert.equal(element('latestWeekly').textContent, staticPrice, id + ': runtime price');
  assert.equal(element('weeklyUnitPrice').textContent, staticUnit, id + ': runtime unit');
  assert.equal(element('referenceObservation').innerHTML, p.observationHtml(sleeve), id + ': runtime observation markup');
  records.push({ id, price: staticPrice, observation: content(html, 'weeklyCount'), count: content(html, 'referenceTradeCount'), unit: staticUnit, status: 'pass' });
}
const indexSource = [...read('index-market.html').matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/gi)].find(match => match[2].includes('function buildMarketIndexView'))[2];
const marketContext = createContext({ console, Date, Intl, URL, URLSearchParams, window: {}, document: { getElementById: element } });
runInContext(read('assets/pricing.js') + '\n' + indexSource.slice(0, indexSource.lastIndexOf('    main();')), marketContext);
marketContext.sleeves = p.sanitizeCatalog(data.sleeves);
runInContext('const view = buildMarketIndexView(sleeves,"week"); const series = buildAveragePriceSeries(view.entries,view.periods,view.periodType); updatePriceSummaryCards(series); renderAiComment(series.at(-1).week,buildMarketCommentStats(series));', marketContext);
const market = read('index-market.html');
for (const id of ['kpiLatestPrice', 'kpiPrevChange', 'kpiPrevPct', 'kpiMonthChange', 'kpiYearChange', 'aiCommentBody']) assert.equal(content(market, id), element(id).textContent, 'market ' + id);
assert.ok(/<svg class="price-index-chart"/.test(market), 'Initial market chart is present');
assert.equal((market.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '').match(/<svg class="price-index-chart"/g) || []).length, 1, 'Market regeneration must not duplicate nested charts');
marketContext.fixture = [{ ...fixture, weeklyPrices: [{ week: '2026-06-01', price: 1000, count: 1 }] }];
const calendarMean = runInContext('(() => { const v = buildMarketIndexView(fixture, "week"); return buildAveragePriceSeries(v.entries, v.periods, v.periodType).at(-1)?.avgPrice; })()', marketContext);
assert.equal(calendarMean, 1000, 'Market includes valid weekly observations on the first of the month');
marketContext.fixture = [monthly];
const monthlyMean = runInContext('(() => { const v = buildMarketIndexView(fixture, "month"); return buildAveragePriceSeries(v.entries, v.periods, v.periodType).at(-1)?.avgPrice; })()', marketContext);
assert.equal(monthlyMean, 4100, 'Explicit monthly data retain their monthly granularity');
fs.mkdirSync(path.join(root, 'reports/site-quality-2026-10-12'), { recursive: true });
fs.writeFileSync(path.join(root, 'reports/site-quality-2026-10-12/price-regression.json'), JSON.stringify({ fixtures: 'pass', products: records, market: 'pass', mismatch_count: 0 }, null, 2));
console.log(`PASS: explicit price fixtures; ${records.length} static/runtime product prices, observations, counts, retail and units; all market KPI values/comment.`);
